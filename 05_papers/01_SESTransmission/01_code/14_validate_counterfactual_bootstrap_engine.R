source('05_papers/01_SESTransmission/01_code/upstream/global_mediation_code/functions.R');source('05_papers/01_SESTransmission/01_code/09_counterfactual_robustness_functions.R')
library(lme4)
W<-Sys.getenv('IJED_MEDIATION_WORK','05_papers/01_SESTransmission/04_output/upstream')
ans<-lapply(c('SES_ARM','DEP_ARM','SES_MYS'),function(id){
 s<-readRDS(file.path(W,'compressed',paste0(id,'.rds')))$s;d<-s$d;pr<-c('status',s$controls,s$sk)
 sg<-general_compress(d,pr);J<-length(sg$n);set.seed(1108);take<-sample.int(J,J,TRUE);mult<-tabulate(take,nbins=J)
 cf<-general_fit(sg,mult)
 groups<-split(seq_len(nrow(d)),d$school,drop=TRUE)
 dd<-rbindlist(lapply(seq_along(take),function(k){z<-copy(d[groups[[take[k]]]]);z[,school:=paste0('resampled_',k)];z}))
 f<-as.formula(paste('PV1READ ~',paste(c(paste0(pr,'_W'),paste0(pr,'_B'),'(1|school)'),collapse='+')))
 m<-lmer(f,data=dd,REML=FALSE);err<-max(abs(cf[names(fixef(m)),1]-fixef(m)))
 stopifnot(err<.02)
 data.table(job=id,comparison='Explicit duplicated-school lmer bootstrap',max_coefficient_error=err)
})
fwrite(rbindlist(ans),'05_papers/01_SESTransmission/04_output/rev2/audit/equalization_robustness_bootstrap_engine_validation.csv');print(rbindlist(ans))
